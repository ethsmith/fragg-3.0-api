#!/usr/bin/env node
// Regenerates src/stats/fields.ts from eco-rating's engine/payload/fields.tsv,
// the engine's list of every payload field by scope with its Go type.
//
//   node scripts/gen-fields.mjs ../../GolandProjects/eco-rating/engine/payload/fields.tsv
//
// Run it whenever the worker moves to an eco-rating version that adds,
// removes or retypes a player or team field.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-fields.mjs PATH/TO/fields.tsv');
  process.exit(2);
}

const rows = readFileSync(src, 'utf8')
  .split(/\r?\n/)
  .filter(Boolean)
  .slice(1)
  .map((line) => {
    const [name, , goType, scope] = line.split('\t');
    return { name, goType, scope };
  });

function numeric(scope) {
  const out = {};
  for (const r of rows) {
    if (r.scope !== scope) continue;
    if (r.goType === 'int') out[r.name] = 'int';
    else if (r.goType === 'float64') out[r.name] = 'float';
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

function render(name, fields) {
  const body = Object.entries(fields)
    .map(([k, v]) => `  ${JSON.stringify(k)}: '${v}',`)
    .join('\n');
  return `export const ${name}: Readonly<Record<string, NumericKind>> = {\n${body}\n};\n`;
}

const out = `// GENERATED by scripts/gen-fields.mjs from eco-rating engine/payload/fields.tsv. Do not edit.
//
// The numeric fields of the payload's player rows and team rows, by Go type:
// 'int' is a counter, 'float' a rate, rating or float total.

export type NumericKind = 'int' | 'float';

${render('PLAYER_FIELDS', numeric('player'))}
${render('TEAM_FIELDS', numeric('team'))}`;

const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'stats', 'fields.ts');
writeFileSync(dest, out);
console.log(`wrote ${dest}`);
