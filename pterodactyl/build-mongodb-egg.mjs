// Writes egg-mongodb.json, embedding mongodb-install.sh as the install script.
// Run from the repo root: node pterodactyl/build-mongodb-egg.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const installScript = readFileSync(join(here, 'mongodb-install.sh'), 'utf8').replace(/\r\n/g, '\n');

const secret = (name, env, description) => ({
  name,
  description,
  env_variable: env,
  default_value: '',
  user_viewable: false,
  user_editable: true,
  rules: 'required|string|min:12|max:128',
  field_type: 'text',
});

const egg = {
  _comment: 'Generated by pterodactyl/build-mongodb-egg.mjs. Import into the panel: Nests > (a nest) > Import Egg.',
  meta: { version: 'PTDL_v2', update_url: null },
  exported_at: '2026-11-23T00:00:00+00:00',
  name: 'MongoDB 8',
  author: 'ethsmith@users.noreply.github.com',
  description:
    'MongoDB 8 for the Fragg 3.0 API. mongod runs in the foreground with authentication always on, ' +
    'data in /home/container/db. Install creates an admin user (root) and an app user (readWrite on one ' +
    'database); reinstalling keeps the data and resets both users to the passwords set here.',
  features: null,
  docker_images: { 'MongoDB 8': 'ghcr.io/parkervcp/yolks:mongodb_8' },
  file_denylist: [],
  // exec: mongod replaces the entrypoint shell as PID 1, so the panel's stop
  // signal reaches it and it shuts down cleanly.
  startup:
    'exec mongod --dbpath /home/container/db --port {{SERVER_PORT}} --bind_ip_all --auth ' +
    '--nounixsocket --wiredTigerCacheSizeGB {{CACHE_SIZE_GB}}',
  config: {
    files: '{}',
    startup: JSON.stringify({ done: 'Waiting for connections' }),
    logs: '{}',
    stop: '^C',
  },
  scripts: {
    installation: {
      script: installScript,
      container: 'mongo:8-noble',
      entrypoint: 'bash',
    },
  },
  variables: [
    {
      name: 'Admin Username',
      description: 'MongoDB user with the root role, for administration (mongosh, mongodump, mongorestore).',
      env_variable: 'MONGO_ADMIN_USER',
      default_value: 'admin',
      user_viewable: true,
      user_editable: true,
      rules: 'required|string|alpha_dash|max:64',
      field_type: 'text',
    },
    secret(
      'Admin Password',
      'MONGO_ADMIN_PASSWORD',
      'Password for the admin user, 12 or more characters. Changing it takes effect on Reinstall (data is kept).',
    ),
    {
      name: 'App Username',
      description: 'MongoDB user the API connects as. It can only read and write the App Database.',
      env_variable: 'MONGO_APP_USER',
      default_value: 'fragg',
      user_viewable: true,
      user_editable: true,
      rules: 'required|string|alpha_dash|max:64',
      field_type: 'text',
    },
    secret(
      'App Password',
      'MONGO_APP_PASSWORD',
      'Password for the app user, 12 or more characters. Changing it takes effect on Reinstall (data is kept).',
    ),
    {
      name: 'App Database',
      description: 'Database the app user may read and write. Use the same name in the API\'s MONGODB_URI.',
      env_variable: 'MONGO_APP_DATABASE',
      default_value: 'fragg',
      user_viewable: true,
      user_editable: true,
      rules: 'required|string|alpha_dash|max:64',
      field_type: 'text',
    },
    {
      name: 'WiredTiger Cache (GB)',
      description:
        "MongoDB's in-memory cache. Keep it at or below half the server's memory limit, or the container " +
        'can be killed for running out of memory.',
      env_variable: 'CACHE_SIZE_GB',
      default_value: '1',
      user_viewable: true,
      user_editable: true,
      rules: 'required|numeric|min:0.25|max:1024',
      field_type: 'text',
    },
  ],
};

writeFileSync(join(here, 'egg-mongodb.json'), JSON.stringify(egg, null, 2) + '\n');
console.log('wrote pterodactyl/egg-mongodb.json');
